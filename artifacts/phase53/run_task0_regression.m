function run_task0_regression()
% Phase 5.3 Task 0: reproduce the Phase 5.2 full regression and record it.
here = fileparts(mfilename('fullpath'));
ev = fullfile(here, 'evidence');
if ~isfolder(ev), mkdir(ev); end
outDir = 'E:\desktop\MATLAB\artifacts\validation\phase53';
if ~isfolder(outDir), mkdir(outDir); end

t0 = tic;
out = evalc('res = run_all(outDir);');
elapsed = toc(t0);

fid = fopen(fullfile(ev, 'task0_regression.log'), 'w');
fwrite(fid, out, 'char');
fclose(fid);

fid = fopen(fullfile(ev, 'task0_regression_summary.json'), 'w');
fwrite(fid, jsonencode(struct('skillPass', res.skillPass, 'skillTotal', res.skillTotal, ...
    'suitesErrored', res.suitesErrored, 'suitesRun', res.suitesRun, ...
    'allSuitesOk', res.allSuitesOk, 'referencesPass', res.references.pass, ...
    'referencesTotal', res.references.total, ...
    'crossdomainPass', res.crossdomain.pass, 'crossdomainTotal', res.crossdomain.total, ...
    'pipelinePass', res.pipeline.pass, 'pipelineTotal', res.pipeline.total, ...
    'skillMatchRate', res.pipeline.skillMatchRate, ...
    'matlabVersion', res.matlabVersion, 'timestamp', res.timestamp, ...
    'elapsedS', elapsed)), 'char');
fclose(fid);

fprintf('TASK0 %d/%d refs %d/%d cd %d/%d pipe %d/%d err %d\n', ...
    res.skillPass, res.skillTotal, res.references.pass, res.references.total, ...
    res.crossdomain.pass, res.crossdomain.total, ...
    res.pipeline.pass, res.pipeline.total, res.suitesErrored);
end