% Routing probe for the Task 3 robotics vocabulary, plus one domain control.
clear functions; rehash;
here = fileparts(mfilename('fullpath'));
repo = fileparts(fileparts(here));
addpath(fullfile(repo, 'skills', 'matlab-orchestrator', 'scripts'));
P = { '四元数和旋转矩阵互相转换，检查 SLERP 插值', ...
      '机械臂正运动学和雅可比矩阵验证', ...
      '机械臂逆运动学求解，关节限位', ...
      '轨迹规划的路径点与速度上限检查', ...
      '两连杆动力学 M C g 与能量守恒', ...
      'EKF 状态估计的 NEES 一致性分析', ...
      '刚体位姿的 SE(3) 正交性检查', ...
      '用 ROS 读取 bag 做传感器融合', ...
      '无人机轨迹跟踪仿真' };
L = {};
for k = 1:numel(P)
    d = mas_route(P{k});
    L{end+1} = sprintf('%-40s -> %-28s %s', P{k}, d.primary, d.decision); %#ok<AGROW>
end
d = mas_route('对实验数据做误差传播分析');
L{end+1} = sprintf('%-40s -> %-28s %s', '对实验数据做误差传播分析 [control]', ...
    d.primary, d.decision);
txt = strjoin(L, sprintf('\n'));
fprintf('%s\n', txt);
fid = fopen(fullfile(here, 'task3_routing.txt'), 'w');
if fid >= 0, fwrite(fid, [txt sprintf('\n')], 'char'); fclose(fid); end
