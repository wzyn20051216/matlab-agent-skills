function S = p58_scoring_v3_replay(evalDir)
%P58_SCORING_V3_REPLAY  Replay the frozen Phase 5.6 results under v3 dimensions.
%
%   S = p58_scoring_v3_replay()
%   S = p58_scoring_v3_replay('<repo parent>/MATLAB-bench-phase56/eval')
%
% Phase 5.7 labelled four stored results "schema valid, numbers wrong". They
% were categorical vocabulary misses (state, stiffnessClassified), not
% arithmetic misses, and one label cannot tell those two apart. This replay
% keeps v1 and v2 exactly as they were written and adds the v3 dimensions, so
% the difference is auditable instead of a re-interpretation:
%
%   * v1 fields must match artifacts/phase57/delivery/delivery_audit.json
%   * v2 replay files are read, never rewritten
%   * every enum-only failure must now read numericalCorrectness=PASS and
%     enumContractValid=FAIL
%   * a second pass declares workflow stages: numerically correct deliveries
%     that never recorded a workflow must NOT become valid
%
% Nothing here is a new experiment and nothing is a Skill effect claim.

here = fileparts(mfilename('fullpath'));
repo = fileparts(fileparts(fileparts(here)));
if nargin < 1 || isempty(evalDir)
    % Derived, never hardcoded: the frozen Phase 5.6 eval tree sits next to the
    % repository, so the default follows wherever this checkout actually lives.
    evalDir = fullfile(fileparts(repo), 'MATLAB-bench-phase56', 'eval');
end
outDir = fullfile(repo, 'artifacts', 'phase58', 'scoring');
if ~isfolder(outDir), mkdir(outDir); end
addpath(fullfile(repo, 'skills', 'matlab-testing-ci', 'scripts'));

answersFile = fullfile(evalDir, 'answers.json');
archiveFile = fullfile(repo, 'artifacts', 'phase57', 'delivery', 'delivery_audit.json');
if ~isfile(answersFile), error('p58_scoring_v3_replay:input', 'missing %s', answersFile); end
if ~isfile(archiveFile), error('p58_scoring_v3_replay:input', 'missing %s', archiveFile); end

arms = ["R1", "R2", "R3"];
taskIds = ["P56-SIG-B", "P56-ODE-N", "P56-SIG-F"];
inputFiles = string(answersFile);
for a = arms
    for id = taskIds
        inputFiles(end+1) = string(fullfile(evalDir, ['arm_' char(a)], ...
            sprintf('result_%s.json', id))); %#ok<AGROW>
    end
end
before = arrayfun(@(p) string(sha256_file(char(p))), inputFiles);

A = jsondecode(fileread(answersFile));
alist = A.tasks; if isstruct(alist), alist = num2cell(alist(:)); end
amap = containers.Map('KeyType', 'char', 'ValueType', 'any');
for k = 1:numel(alist), amap(char(alist{k}.id)) = alist{k}; end
archived = jsondecode(fileread(archiveFile));

stages = {{'skillSelected', 'referencesLoaded', 'mcpExecuted', 'checksRun'}};
rows = v3_rows();
for a = arms
    for k = 1:numel(taskIds)
        id = char(taskIds(k));
        rf = fullfile(evalDir, ['arm_' char(a)], sprintf('result_%s.json', id));
        sealed = struct('schema', 'mas-delivery-contract/1', ...
            'profile', 'mas-result/1-legacy', 'taskId', id, ...
            'expectedVerdict', char(amap(id).verdict), 'fields', amap(id).fields);
        D1 = mas_delivery_check(rf, sealed, 'verbose', false);
        staged = sealed;
        staged.workflow = struct('required', true, 'stages', stages);
        D2 = mas_delivery_check(rf, staged, 'verbose', false);
        ar = archived.rows(strcmp({archived.rows.arm}, char(a)) & ...
             strcmp({archived.rows.taskId}, id));
        rows(end+1) = struct( ...
            'arm', char(a), 'taskId', id, ...
            'v1Overall', D1.overall, 'v1Math', D1.math.status, ...
            'archiveOverall', char(ar(1).overall), 'archiveMath', char(ar(1).math), ...
            'v1Unchanged', strcmp(D1.overall, char(ar(1).overall)) && ...
                strcmp(D1.math.status, char(ar(1).math)), ...
            'numericalCorrectness', D1.dimensions.numericalCorrectness.status, ...
            'enumContractValid', D1.dimensions.enumContractValid.status, ...
            'engineeringVerdictCorrect', D1.dimensions.engineeringVerdictCorrect.status, ...
            'structuralSchemaValid', D1.dimensions.structuralSchemaValid.status, ...
            'workflowCompletedSealed', D1.dimensions.workflowCompleted.status, ...
            'workflowCompletedStaged', D2.dimensions.workflowCompleted.status, ...
            'withinBudget', D1.dimensions.withinBudget.status, ...
            'deliveryValidSealed', D1.dimensions.deliveryValid.status, ...
            'deliveryValidStaged', D2.dimensions.deliveryValid.status, ...
            'enumBadFields', {bad_field_names(D1, 'exact')}, ...
            'numericBadFields', {bad_field_names(D1, 'numeric')}); %#ok<AGROW>
    end
end

after = arrayfun(@(p) string(sha256_file(char(p))), inputFiles);
v1Preserved = all([rows.v1Unchanged]);
enumOnlyFail = rows(strcmp({rows.v1Math}, 'FAIL'));
enumOnlyOK = ~isempty(enumOnlyFail) && ...
    all(strcmp({enumOnlyFail.numericalCorrectness}, 'PASS')) && ...
    all(strcmp({enumOnlyFail.enumContractValid}, 'FAIL')) && ...
    all(~cellfun(@isempty, {enumOnlyFail.enumBadFields})) && ...
    all(cellfun(@isempty, {enumOnlyFail.numericBadFields}));
numericalFails = rows(strcmp({rows.numericalCorrectness}, 'FAIL'));
% The relaxation guard: a delivery that v3 calls valid must not become valid
% simply because its numbers are right. Once the contract demands workflow
% stages, those runs must drop to UNDETERMINED.
sealedOK = rows(strcmp({rows.deliveryValidSealed}, 'PASS'));
noRelaxation = ~isempty(sealedOK) && ...
    all(strcmp({sealedOK.workflowCompletedStaged}, 'UNRECORDED')) && ...
    all(~strcmp({sealedOK.deliveryValidStaged}, 'PASS')) && ...
    all(strcmp({sealedOK.deliveryValidStaged}, 'UNDETERMINED')) && ...
    all(strcmp({sealedOK.numericalCorrectness}, 'PASS'));

S = struct();
S.schema = 'mas-phase58-scoring-v3-replay/1';
S.generatedAt = datestr(now, 31);
S.evalDir = evalDir;
S.kind = 'retrospective replay of stored results under protocol v3';
S.claimLimit = ['stored Phase 5.6 results re-scored; not a new experiment, not a ' ...
    'Skill effect, and not evidence about client installation'];
S.dimensions = {{'numericalCorrectness', 'enumContractValid', ...
    'engineeringVerdictCorrect', 'structuralSchemaValid', 'workflowCompleted', ...
    'withinBudget', 'deliveryValid'}};
S.mapping = struct('v2Dimension', {'executed', 'route', 'tool', 'verdict', 'fields', ...
        'integrity', 'schema', 'budget'}, ...
    'v3Dimension', {'deliveryValid', 'workflowCompleted', 'workflowCompleted', ...
        'engineeringVerdictCorrect', 'numericalCorrectness + enumContractValid', ...
        'deliveryValid', 'structuralSchemaValid', 'withinBudget'}, ...
    'note', {'error path only', 'stage evidence, when declared', ...
        'stage evidence, when declared', 'never coerced', ...
        'split: categorical spellings are no longer arithmetic', ...
        'false accept and runner errors aggregate only', ...
        'profile, taskId, required fields, units', 'usage vs declared limits'});
S.counts = struct('nResults', numel(rows), ...
    'v1Unchanged', nnz([rows.v1Unchanged]), ...
    'mathFail', numel(enumOnlyFail), ...
    'enumOnlyFail', nnz(strcmp({enumOnlyFail.enumContractValid}, 'FAIL')), ...
    'numericalFail', numel(numericalFails), ...
    'verdictCorrect', nnz(strcmp({rows.engineeringVerdictCorrect}, 'PASS')), ...
    'structuralValid', nnz(strcmp({rows.structuralSchemaValid}, 'PASS')));
S.rules = struct( ...
    'enumCountedAsNumericalError', false, ...
    'numericallyCorrectRescuesContract', false, ...
    'historicalV1FieldsRewritten', false, ...
    'frozenThresholdsModified', false);
S.inputsUnchanged = isequal(before, after);
S.workflowStages = stages{1};
S.inputFiles = cellstr(inputFiles);
S.inputsSha256 = cellstr(before);
S.v1Preserved = v1Preserved;
S.enumOnlyFailuresSeparated = enumOnlyOK;
S.workflowNotRelaxed = noRelaxation;
S.rows = rows;
S.pass = S.inputsUnchanged && v1Preserved && enumOnlyOK && noRelaxation && ...
    numel(enumOnlyFail) == 4 && S.counts.verdictCorrect == numel(rows) && ...
    isempty(numericalFails) && ...
    nnz(strcmp({rows.deliveryValidSealed}, 'PASS')) == 5;

fid = fopen(fullfile(outDir, 'scoring_v3_replay.json'), 'w');
if fid < 0, error('p58_scoring_v3_replay:write', 'cannot write %s', fullfile(outDir, 'scoring_v3_replay.json')); end
fwrite(fid, jsonencode(S, 'PrettyPrint', true), 'char'); fclose(fid);

fprintf('%-3s %-11s %-8s | %-9s %-9s %-8s %-9s %-13s %-9s\n', ...
    'arm', 'task', 'v1 math', 'numeric', 'enum', 'verdict', 'struct', 'wf staged', 'budget');
for k = 1:numel(rows)
    r = rows(k);
    fprintf('%-3s %-11s %-8s | %-9s %-9s %-8s %-9s %-13s %-9s -> delivery %s (staged %s)\n', ...
        r.arm, r.taskId, r.v1Math, r.numericalCorrectness, r.enumContractValid, ...
        r.engineeringVerdictCorrect, r.structuralSchemaValid, ...
        r.workflowCompletedStaged, r.withinBudget, r.deliveryValidSealed, ...
        r.deliveryValidStaged);
end
fprintf('\nv1 preserved %d/%d, v1-math FAIL %d (all enum-only: %d), numerical FAIL %d, inputs unchanged %d\n', ...
    S.counts.v1Unchanged, S.counts.nResults, numel(enumOnlyFail), ...
    S.counts.enumOnlyFail, numel(numericalFails), S.inputsUnchanged);
fprintf('pass=%d -> %s\n', S.pass, fullfile(outDir, 'scoring_v3_replay.json'));

    function names = bad_field_names(D, axis)
        names = {};
        if ~strcmp(D.math.status, 'FAIL'), return; end
        for q = 1:numel(D.math.checks)
            c = D.math.checks(q);
            if c.ok, continue; end
            if strcmp(axis, 'exact') && strcmp(c.kind, 'exact')
                names{end+1} = c.id; %#ok<AGROW>
            elseif strcmp(axis, 'numeric') && (strcmp(c.kind, 'numeric') || strcmp(c.kind, 'domain'))
                names{end+1} = c.id; %#ok<AGROW>
            end
        end
    end
end

function rows = v3_rows()
rows = struct('arm', {}, 'taskId', {}, 'v1Overall', {}, 'v1Math', {}, ...
    'archiveOverall', {}, 'archiveMath', {}, 'v1Unchanged', {}, ...
    'numericalCorrectness', {}, 'enumContractValid', {}, ...
    'engineeringVerdictCorrect', {}, 'structuralSchemaValid', {}, ...
    'workflowCompletedSealed', {}, 'workflowCompletedStaged', {}, ...
    'withinBudget', {}, 'deliveryValidSealed', {}, 'deliveryValidStaged', {}, ...
    'enumBadFields', {}, 'numericBadFields', {});
end

function s = sha256_file(p)
fid = fopen(p, 'r');
if fid < 0, error('p58_scoring_v3_replay:hash', 'cannot open %s', p); end
b = fread(fid, Inf, '*uint8'); fclose(fid);
md = java.security.MessageDigest.getInstance('SHA-256');
d = typecast(md.digest(b), 'uint8');
s = lower(reshape(dec2hex(d)', 1, []));
end
