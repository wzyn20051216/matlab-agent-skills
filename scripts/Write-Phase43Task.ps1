param(
    [Parameter(Mandatory)][string]$TaskId,
    [Parameter(Mandatory)][string]$OutputPath
)

# Write the MATLAB task script for one Phase 4.3 benchmark task.
#
# This is the SINGLE SOURCE OF TRUTH for the task code: every group (R1/R2/R3)
# runs exactly this file. The task prints one machine-readable line,
# "MAS_RESULT {json}", which the grader parses -- the grader never reads the
# surrounding prose.

$ErrorActionPreference = "Stop"

switch ($TaskId) {
    "B1" {
        $body = @'
A = [4 -1 2; -1 4 -1; 2 -1 4]; b = [11; -16; 17];
x = A\b; residual = norm(A*x - b);
fprintf('MAS_RESULT {"x":[%.15g,%.15g,%.15g],"residual":%.15g}\n', x(1), x(2), x(3), residual);
'@
    }
    "B2" {
        $body = @'
L = tf(10, [1 3 2]);
[gm, pm] = margin(L);
loopStable = all(real(pole(feedback(L,1))) < 0);
fprintf('MAS_RESULT {"pmDeg":%.15g,"gm":%.15g,"loopStable":%d}\n', pm, gm, loopStable);
'@
    }
    "B3" {
        $body = @'
fs = 1000; t = 0:1/fs:1-1/fs; x = sin(2*pi*10*t);
X = abs(fft(x))/numel(t)*2; [~, peakBin] = max(X);
fprintf('MAS_RESULT {"ampAt10":%.15g,"peakBin":%d}\n', X(peakBin), peakBin);
'@
    }
    "B4" {
        $body = @'
xv = [1 2 3 4 5]; yv = [2.1 4.0 6.1 7.9 10.2];
p = polyfit(xv, yv, 1);
fprintf('MAS_RESULT {"slope":%.15g,"intercept":%.15g}\n', p(1), p(2));
'@
    }
    "B5" {
        $body = @'
L1 = 1.0; L2 = 0.5; q1 = deg2rad(30); q2 = deg2rad(45);
xx = L1*cos(q1) + L2*cos(q1+q2); yy = L1*sin(q1) + L2*sin(q1+q2);
fprintf('MAS_RESULT {"x":%.15g,"y":%.15g}\n', xx, yy);
'@
    }
    "B6" {
        $body = @'
f = fullfile(tempdir, 'p43_b6.m');
fid = fopen(f, 'w');
fwrite(fid, sprintf('function y = f(x)\n%%#codegen\nn = length(x);\ny = zeros(1,n);\nfor k = 1:n\n  y(k) = x(k)^2;\nend\nend\n'));
fclose(fid);
r = mas_codegen_ready(f);
fprintf('MAS_RESULT {"verdict":"%s"}\n', r.verdict);
'@
    }
    default { throw "unknown task id $TaskId" }
}

$header = "% Phase 4.3 benchmark task $TaskId`n% Generated by Write-Phase43Task.ps1 -- do not edit by hand.`n"
Set-Content -LiteralPath $OutputPath -Value ($header + $body) -Encoding ascii